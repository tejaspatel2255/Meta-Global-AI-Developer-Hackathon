"""Export JSON Schema from Pydantic; emit TypeScript enums for the UI."""

from __future__ import annotations

import argparse
import json
from enum import Enum
from pathlib import Path
from types import UnionType
from typing import Union, get_args, get_origin

from benchguard.contracts.enums import (
    AttrCategory,
    ErrorType,
    PredicateStatus,
    Role,
    SessionStatus,
    StepStatus,
    TickTrigger,
)
from benchguard.contracts.events import Event
from benchguard.contracts.ir import Procedure
from benchguard.contracts.observation import Observation
from benchguard.contracts.state import SessionState

_ENUMS: dict[str, type[Enum]] = {
    "PredicateStatus": PredicateStatus,
    "StepStatus": StepStatus,
    "ErrorType": ErrorType,
    "Role": Role,
    "AttrCategory": AttrCategory,
    "TickTrigger": TickTrigger,
    "SessionStatus": SessionStatus,
}


def _ts_enums() -> str:
    lines = [
        "/* Generated by `make schemas` from Pydantic contracts. Do not edit. */",
        "",
    ]
    for name, enum_cls in _ENUMS.items():
        lines.append(f"export type {name} =")
        members = list(enum_cls)
        for i, member in enumerate(members):
            ending = ";" if i == len(members) - 1 else ""
            lines.append(f'  | "{member.value}"{ending}')
        lines.append("")
    return "\n".join(lines) + "\n"


def _event_schema() -> dict[str, object]:
    annotated_args = get_args(Event)
    union = annotated_args[0]
    origin = get_origin(union)
    if origin not in {Union, UnionType}:
        msg = f"Event union origin unexpected: {origin!r}"
        raise TypeError(msg)
    return {"oneOf": [model.model_json_schema() for model in get_args(union)]}


def export(out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    bundle = {
        "Procedure": Procedure.model_json_schema(),
        "Observation": Observation.model_json_schema(),
        "SessionState": SessionState.model_json_schema(),
        "Event": _event_schema(),
    }
    (out_dir / "schema.json").write_text(
        json.dumps(bundle, indent=2) + "\n",
        encoding="utf-8",
    )
    (out_dir / "enums.ts").write_text(_ts_enums(), encoding="utf-8")
    (out_dir / "index.ts").write_text(
        "export type {\n"
        "  AttrCategory,\n"
        "  ErrorType,\n"
        "  PredicateStatus,\n"
        "  Role,\n"
        "  SessionStatus,\n"
        "  StepStatus,\n"
        "  TickTrigger,\n"
        '} from "./enums";\n',
        encoding="utf-8",
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("frontend/src/contracts"),
    )
    args = parser.parse_args()
    export(args.out)
    print(f"wrote schemas to {args.out}")


if __name__ == "__main__":
    main()
